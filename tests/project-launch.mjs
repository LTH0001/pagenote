import assert from 'node:assert/strict';
import path from 'node:path';
import { createRequire } from 'node:module';
const { projectArgument, createProjectLauncher } = createRequire(import.meta.url)('../desktop/project-launch.cjs');
const calls = [], errors = [];
const launcher = createProjectLauncher({ open: async f => { if(f === 'bad') throw Error('bad manifest'); calls.push(f); }, onError: (e,f) => errors.push([e.message,f]) });
await launcher.enqueue('cold-start');
await launcher.enqueue('during-startup');
assert.deepEqual(calls, []);
await launcher.ready();
assert.deepEqual(calls, ['cold-start','during-startup']);
await launcher.enqueue('bad');
await launcher.enqueue('after-error');
assert.deepEqual(errors, [['bad manifest','bad']]);
assert.equal(calls.at(-1), 'after-error');
assert.equal(projectArgument(['app','课件/project.pagenote'], process.cwd()), path.resolve('课件/project.pagenote'));
assert.equal(projectArgument(['app','project.page-notes.json']),path.resolve('project.page-notes.json'));
assert.equal(projectArgument(['app','--flag']), null);
console.log('PASS queued cold/warm project launches and visible error recovery');
